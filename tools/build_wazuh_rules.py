"""Generate integrations/wazuh/lyss_rules.xml from the specification.

    python tools/build_wazuh_rules.py           write the rules
    python tools/build_wazuh_rules.py --check   exit 1 if the published file is out of date

Besides the generic rules (scan, finding, regression, fix, collection error, discovery, test), every
assessable control gets a "finding" rule and a "regression" rule carrying its NIST SP 800-53 groups
(nist_800_53_XX.N, Wazuh's format), so LYSS results appear in Wazuh's NIST 800-53 compliance
dashboard next to the other sources. Controls without text yet (drafts) get no rule.
"""

import argparse
import re
import sys
from pathlib import Path
from xml.sax.saxutils import escape

import yaml

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "spec" / "lyss-spec.yaml"
OUT = ROOT / "integrations" / "wazuh" / "lyss_rules.xml"

FIRST_FINDING_ID = 100810     # 100810-100839: one finding rule per control
FIRST_REGRESSION_ID = 100840  # 100840-100869: one regression rule per control
MAX_CONTROLS = 30
FINDING_LEVEL = {1: 7, 2: 5}  # Baseline failures weigh more than Hardened ones
REGRESSION_LEVEL = 10         # install.sh --regression-level N changes it on an installation

HEADER = """<!--
  SPDX-License-Identifier: AGPL-3.0-only
  Copyright 2026 Mouad Lyaazale. Additional terms (author attribution, names): see NOTICE.

  Wazuh rules for LYSS (Lyaazale Switch Security) SIEM events, specification {version}.
  GENERATED by tools/build_wazuh_rules.py from spec/lyss-spec.yaml: do not edit by hand.
  LYSS sends JSON events {{"lyss": {{...}}}} over syslog (decoder "lyss", lyss_decoders.xml) or writes
  them to a JSON-lines file read by a Wazuh agent (built-in "json" decoder).
  Install: sudo sh install.sh (copies the decoder and these rules, checks, restarts the manager).
  Rule ids 100800-100869: change them if they collide with your own local rules.
-->
<group name="lyss,network_switch,">

  <!-- events received over syslog (lyss_decoders.xml) -->
  <rule id="100800" level="0">
    <decoded_as>lyss</decoded_as>
    <field name="lyss.event">\\.+</field>
    <description>LYSS: switch security event</description>
  </rule>

  <!-- events read from the LYSS events file by a Wazuh agent (<log_format>json</log_format>) -->
  <rule id="100809" level="0">
    <decoded_as>json</decoded_as>
    <field name="lyss.event">\\.+</field>
    <description>LYSS: switch security event</description>
  </rule>

  <rule id="100801" level="3">
    <if_sid>100800, 100809</if_sid>
    <field name="lyss.event">^scan$</field>
    <description>LYSS: $(lyss.device) assessed, level $(lyss.level), $(lyss.fail) failed control(s)</description>
    <group>lyss_scan,</group>
  </rule>

  <!-- a failed control; the per-control rules below refine it (level and NIST 800-53 groups) -->
  <rule id="100802" level="5">
    <if_sid>100800, 100809</if_sid>
    <field name="lyss.event">^finding$</field>
    <description>LYSS: $(lyss.device) fails $(lyss.control) (Level $(lyss.control_level)): $(lyss.title)</description>
    <group>lyss_finding,</group>
  </rule>

  <!-- a control that passed at the previous scan fails now (configuration changed) -->
  <rule id="100804" level="{regression_level}">
    <if_sid>100800, 100809</if_sid>
    <field name="lyss.event">^regression$</field>
    <description>LYSS: new failure on $(lyss.device): $(lyss.control) $(lyss.title)</description>
    <group>lyss_regression,configuration_changed,</group>
  </rule>

  <rule id="100805" level="3">
    <if_sid>100800, 100809</if_sid>
    <field name="lyss.event">^fixed$</field>
    <description>LYSS: $(lyss.device) now passes $(lyss.control) $(lyss.title)</description>
    <group>lyss_fixed,</group>
  </rule>

  <rule id="100806" level="6">
    <if_sid>100800, 100809</if_sid>
    <field name="lyss.event">^collection_error$</field>
    <description>LYSS: $(lyss.device) could not be collected: $(lyss.message)</description>
    <group>lyss_error,</group>
  </rule>

  <rule id="100807" level="6">
    <if_sid>100800, 100809</if_sid>
    <field name="lyss.event">^discovered$</field>
    <description>LYSS: $(lyss.count) unmanaged switch(es) discovered on the network</description>
    <group>lyss_discovery,</group>
  </rule>

  <rule id="100808" level="3">
    <if_sid>100800, 100809</if_sid>
    <field name="lyss.event">^test$</field>
    <description>LYSS: test event received</description>
    <group>lyss_test,</group>
  </rule>
"""

PER_CONTROL = """
  <rule id="{id}" level="{level}">
    <if_sid>{parent}</if_sid>
    <field name="lyss.control">^{control}$</field>
    <description>{description}</description>
    <group>{groups}</group>
  </rule>
"""


def nist_groups(refs) -> list[str]:
    """NIST SP 800-53 references ("AC-17(2)", "IA-5") -> Wazuh groups ("nist_800_53_AC.17")."""
    out = []
    for ref in refs or []:
        m = re.match(r"^([A-Z]{2})-(\d+)", str(ref))
        if m and (g := f"nist_800_53_{m.group(1)}.{m.group(2)}") not in out:
            out.append(g)
    return out


def assessable(spec: dict) -> list[dict]:
    return [c for c in spec["controls"] if c.get("statement")]


def build(spec: dict) -> str:
    controls = assessable(spec)
    if len(controls) > MAX_CONTROLS:
        raise SystemExit(f"{len(controls)} controls: more than the {MAX_CONTROLS} rule ids reserved per kind")
    parts = [HEADER.format(version=spec["spec_version"], regression_level=REGRESSION_LEVEL)]
    parts.append("\n  <!-- ======== per-control rules (NIST SP 800-53 groups for Wazuh's compliance dashboard) ======== -->\n")
    for i, c in enumerate(controls):
        nist = nist_groups(c.get("mappings", {}).get("nist_800_53r5"))
        level = int(c["level"])
        base = ["lyss_finding"] + (["lyss_baseline"] if level == 1 else [])
        parts.append(PER_CONTROL.format(
            id=FIRST_FINDING_ID + i, level=FINDING_LEVEL.get(level, 5), parent=100802, control=c["id"],
            description=f"LYSS: $(lyss.device) fails {c['id']} (Level {level}): {escape(c['title'])}",
            groups=",".join(base + nist) + ","))
    for i, c in enumerate(controls):
        nist = nist_groups(c.get("mappings", {}).get("nist_800_53r5"))
        parts.append(PER_CONTROL.format(
            id=FIRST_REGRESSION_ID + i, level=REGRESSION_LEVEL, parent=100804, control=c["id"],
            description=f"LYSS: new failure on $(lyss.device): {c['id']} {escape(c['title'])}",
            groups=",".join(["lyss_regression", "configuration_changed"] + nist) + ","))
    parts.append("\n</group>\n")
    return "".join(parts)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if the published rules are out of date")
    args = ap.parse_args(argv)
    text = build(yaml.safe_load(SPEC.read_text(encoding="utf-8")))
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("Wazuh rules out of date: run python tools/build_wazuh_rules.py")
            return 1
        print("Wazuh rules up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"written {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
